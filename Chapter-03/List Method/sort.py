# ---------------------------------------------------------------------------------------------------

# List in Ascending Order
list = [2, 1, 3]
print(list.append(4))
print(list.sort())
print(list)  # 1, 2, 3, 4


# ---------------------------------------------------------------------------------------------------

# List in Descending Order
list = [2, 1, 3]
print(list.sort(reverse=True))
print(list)  # 3, 2, 1


